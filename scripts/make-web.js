// Turns web/index.html (the same file as the website) into src/web.js, which the app bundles,
// and puts the hang-up sound inside the app (src/sounds.js), so nothing ever comes from the internet.
// The GitHub build runs this by itself, so updating the app = replacing web/index.html.
// Optional: put your own hang-up sound in web/sounds/ (a file whose name starts with "hang",
// e.g. hangup.mp3). Without one, the app uses a soft built-in "call ended" tone.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const ROOT = path.join(__dirname, "..");
const TYPES = { mp3: "audio/mpeg", m4a: "audio/mp4", aac: "audio/aac", wav: "audio/wav", caf: "audio/x-caf", aif: "audio/aiff", aiff: "audio/aiff" };

/* ---------- the page ---------- */
const html = fs.readFileSync(path.join(ROOT, "web", "index.html"), "utf8");
if (!html.includes("ReactNativeWebView") || !html.includes("__NATIVE")) {
  throw new Error("web/index.html is too old: it has no app bridge");
}
fs.writeFileSync(
  path.join(ROOT, "src", "web.js"),
  "// Generated from web/index.html — don't edit by hand.\nexport default " + JSON.stringify(html) + ";\n"
);
console.log("src/web.js written (" + html.length + " chars)");

/* ---------- the hang-up sound ---------- */
// A soft two-note "call ended" tone (22 kHz mono WAV), used when web/sounds has no hang-up file.
function builtInTone() {
  const rate = 22050;
  const total = Math.ceil(rate * 0.58);
  const mix = new Float64Array(total);
  const notes = [ // [frequency Hz, start s, length s]
    [880, 0.0, 0.17],
    [659.25, 0.18, 0.38],
  ];
  for (const [f, t0, len] of notes) {
    const s0 = Math.floor(t0 * rate);
    const n = Math.floor(len * rate);
    const fade = Math.floor(0.012 * rate);
    for (let i = 0; i < n && s0 + i < total; i++) {
      const t = i / rate;
      const env = Math.min(1, t / 0.006) * Math.exp(-t * 7) * Math.min(1, (n - i) / fade);
      mix[s0 + i] += (Math.sin(2 * Math.PI * f * t) + 0.18 * Math.sin(4 * Math.PI * f * t)) * env * 0.32;
    }
  }
  const data = Buffer.alloc(total * 2);
  for (let i = 0; i < total; i++) data.writeInt16LE(Math.max(-32767, Math.min(32767, Math.round(mix[i] * 32767))), i * 2);
  const head = Buffer.alloc(44);
  head.write("RIFF", 0, "ascii");
  head.writeUInt32LE(36 + data.length, 4);
  head.write("WAVE", 8, "ascii");
  head.write("fmt ", 12, "ascii");
  head.writeUInt32LE(16, 16);
  head.writeUInt16LE(1, 20); // PCM
  head.writeUInt16LE(1, 22); // mono
  head.writeUInt32LE(rate, 24);
  head.writeUInt32LE(rate * 2, 28);
  head.writeUInt16LE(2, 32);
  head.writeUInt16LE(16, 34);
  head.write("data", 36, "ascii");
  head.writeUInt32LE(data.length, 40);
  return Buffer.concat([head, data]);
}

function pickHangup() {
  const dir = path.join(ROOT, "web", "sounds");
  let list = [];
  try { list = fs.readdirSync(dir).sort(); } catch (e) {}
  for (const f of list) {
    const ext = (f.split(".").pop() || "").toLowerCase();
    if (!/^hang/i.test(f) || !TYPES[ext]) continue;
    const buf = fs.readFileSync(path.join(dir, f));
    if (buf.length > 200 && buf.length < 8 * 1024 * 1024) return { buf, ext, from: "web/sounds/" + f };
  }
  const def = path.join(ROOT, "assets", "hangup-default.wav");
  if (!fs.existsSync(def)) fs.writeFileSync(def, builtInTone());
  return { buf: fs.readFileSync(def), ext: "wav", from: "assets/hangup-default.wav" };
}

const h = pickHangup();
const sig = "h" + h.buf.length + "-" + crypto.createHash("sha1").update(h.buf).digest("hex").slice(0, 10);
const sounds = { "hangup.mp3": "data:" + TYPES[h.ext] + ";base64," + h.buf.toString("base64") };
fs.writeFileSync(
  path.join(ROOT, "src", "sounds.js"),
  "// Generated by scripts/make-web.js — don't edit by hand.\n" +
    "export const SIG = " + JSON.stringify(sig) + ";\n" +
    "export default " + JSON.stringify(sounds) + ";\n"
);
console.log("src/sounds.js written (hang-up sound: " + h.from + ", " + h.buf.length + " bytes)");
